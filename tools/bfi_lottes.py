#!/usr/bin/env python3
# BFI brightness-preserving (Lottes-style) tables for the hz120 build.
#
# For each output code c (treated as sRGB, GAMMA=2.4, exactly the
# Blur Busters / Lottes reference shader's transfer pair), the linear-light
# photon budget of the pixel over one content frame is L = 2*v (gain 1.0:
# unchanged average brightness). The lit refresh carries HI = encode(min(1,L))
# and the other refresh carries LO = encode(L - min(1,L)), so dark/mid pixels
# (v <= 0.5) land wholly in one refresh (full 50 % clarity) and only bright
# pixels spill over, with no loss of average brightness.
#
# The GBA frame buffer holds 18-bit RGB666 (5-bit colour through the
# colourshade brightness stage), expanded to RGB8 as {6 bits, 2'b0}, so each
# channel needs a 64-entry table over codes i*4. The sim reads the same
# mapping from sim/scanlines/bfi_lottes.hex (256-entry per-code {HI,LO}).
#
# Usage: python3 tools/bfi_lottes.py   (run from the repo root)
# Prints the Verilog assigns to paste into src/gba2hdmi.sv (HZ120 block).
# The sim table is generated by:
#   python3 tools/bfi_lottes.py --hex > sim/scanlines/bfi_lottes.hex
import sys

GAMMA = 2.4  # reference shader GAMMA constant (crt-simulator.glsl)

def srgb2linear(c):
    return ((c + 0.055) / 1.055) ** GAMMA if c > 0.04045 else c / 12.92

def linear2srgb(v):
    return v * 12.92 if v <= 0.0031308 else v ** (1.0 / GAMMA) * 1.055 - 0.055

def pair(code):
    v = srgb2linear(code / 255.0)
    L = 2.0 * v
    hi = min(255, max(0, round(255 * linear2srgb(min(1.0, L)))))
    lo = min(255, max(0, round(255 * linear2srgb(L - min(1.0, L)))))
    return hi, lo

if '--hex' in sys.argv:
    # 256-entry per-code {HI,LO} for the sim (sim/scanlines/bfi_lottes.hex)
    for code in range(256):
        h, l = pair(code)
        sys.stdout.write(f"{h:02x}{l:02x}\n")
else:
    print("// BEGIN Lottes tables (tools/bfi_lottes.py, sRGB GAMMA=2.4).")
    print("// Per channel 6-bit value: HI = lit-refresh value, LO = remainder refresh.")
    hi = [pair(i * 4)[0] for i in range(64)]
    lo = [pair(i * 4)[1] for i in range(64)]
    for i in range(64):
        print(f"// [{i:2d}] {i * 4:02x} -> HI {hi[i]:02x} LO {lo[i]:02x}")
    print("// HI table (lit refresh), indexed by channel 6-bit value:")
    for i in range(64):
        print(f"assign BFI_HI[{i}] = 8'h{hi[i]:02x};")
    print("// LO table (remainder refresh), indexed by channel 6-bit value:")
    for i in range(64):
        print(f"assign BFI_LO[{i}] = 8'h{lo[i]:02x};")
    bhi, blo = pair(0x30)  # border colour 303030
    print(f"// border 303030 -> HI 24'h{bhi:02x}{bhi:02x}{bhi:02x} LO 24'h{blo:02x}{blo:02x}{blo:02x}")
    worst = 0.0
    for code in range(256):
        h, l = pair(code)
        v = srgb2linear(code / 255.0)
        worst = max(worst, abs(srgb2linear(h / 255.0) + srgb2linear(l / 255.0) - 2 * v))
    print(f"// worst average-light error: {worst:.5f} linear ({100 * worst:.3f}% of full white).", file=sys.stderr)
